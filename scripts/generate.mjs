#!/usr/bin/env node
// Generates skills/agentfeed-briefs/SKILL.md and references/*.md from the AgentFeed code, so the skill cannot drift from the server.
//   node scripts/generate.mjs [--repo <agentfeed clone>] [--check]
// --check writes nothing: it exits 1 and names the files that differ from what the code would generate now.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
const repo = path.resolve(arg('--repo') || process.env.AGENTFEED_REPO || path.join(root, '..', 'agentfeed'));
const check = process.argv.includes('--check');

function facts() {
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'afs-'));
  try {
    const out = execFileSync(process.execPath, ['--require', path.join(repo, 'test/helpers/af-test-preload.js'), path.join(here, 'extract-facts.cjs')],
      { cwd: scratch, env: { PATH: process.env.PATH, AF_ROOT: repo, AGENTFEED_DB: path.join(scratch, 'af.db'), OVERHANG_DB_PATH: path.join(scratch, 'overhang.db'), LIQ_DB: path.join(scratch, 'liq.db') }, encoding: 'utf8', maxBuffer: 1 << 24 });
    return JSON.parse(out.trim().split('\n').pop());
  } finally { fs.rmSync(scratch, { recursive: true, force: true }); }
}
const sha = (() => { try { return execFileSync('git', ['-C', repo, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { return 'unknown'; } })();

const F = facts();
const WORDS = ['No', 'One', 'Two', 'Three', 'Four', 'Five'];
const money = (n) => `$${n}`;
const callPrice = (usd) => money(usd);
const first = F.routes[0];
const paceS = F.passes[0].pace_s;
const vars = {
  package_version: fs.readFileSync(path.join(root, 'VERSION'), 'utf8').trim(),
  origin: F.origin,
  count_words: WORDS[F.routes.length] || String(F.routes.length),
  first_route: first.route,
  first_sample: first.sample,
  pace_s: String(paceS),
  keys_url: `${F.origin}${F.keys_page}`,
  routes_table: ['| Brief | Route | Price per call |', '|---|---|---|', ...F.routes.map((r) => `| ${r.title} | \`GET ${r.route}\` | ${callPrice(r.usd)} |`)].join('\n'),
  questions: F.routes.map((r) => `- ${r.question} -> \`${r.route}\``).join('\n'),
  signals_table: ['| Signal | Route | Price per call |', '|---|---|---|', ...F.signal_routes.map((r) => `| ${r.title} | \`GET ${r.shown}\` | ${callPrice(r.usd)} |`)].join('\n'),
  signal_questions: F.signal_routes.map((r) => `- ${r.question} -> \`${r.shown}\``).join('\n') + `\n\nThe pass paces each route once per ${F.passes[0].pace_s} seconds per key. \`${F.signal_routes.find((r) => /coin/.test(r.route)).shown}\` keeps ONE clock for every coin: to read several coins at once call \`/api/signal-board?coins=BTC,ETH,SOL\`.`,
  passes_text: [
    'A key can be one of three things:',
    '',
    ...F.passes.map((p) => `- **${p.label}** (\`GET ${p.path}\`, ${money(p.usd)} flat, ${p.days === 1 ? '24 hours' : `${p.days} days`}): one flat key for the briefs and the perp signal routes, good only on ${p.routes.map((r) => `\`${F.signal_routes.find((x) => x.route === r)?.shown || r}\``).join(', ')}, nothing drawn per call, one call per route every ${p.pace_s} seconds per key. Non-refundable, no top-up, a bearer secret: anyone who holds the key uses the pass.`),
    '- **Prepaid pack** (\`GET /api/keys/buy-1\`, \`buy-5\`, \`buy-20\`): a balance; each call draws half the route price (minimum $0.0005). Works on every AgentFeed route.',
    '',
    `Both can be bought at ${F.origin}${F.keys_page} in a browser with a Base wallet; the page makes the key in the browser and sends AgentFeed only its hash. A stock x402 client with its default $1 spend cap can buy the ${money(F.passes[1].usd)} day pass as is.`,
  ].join('\n').replace(/\\`/g, '`'),
  routes_ref: '',
};
const render = (tpl) => tpl.replace(/\{\{(\w+)\}\}/g, (_m, k) => { if (!(k in vars)) throw new Error(`template variable ${k} has no value`); return vars[k]; });

const routesRef = [
  '# Routes, prices and pass terms',
  '',
  `Generated by scripts/generate.mjs from the AgentFeed code. Do not edit by hand. The live 402 challenge of each route is the authority on its price; prices can change.`,
  '',
  `Service: ${F.origin}. Header for a key or pass: \`${F.header}: afk_...\` (or \`Authorization: Bearer afk_...\`).`,
  '',
  ...F.routes.flatMap((r) => [`## ${r.title}: \`GET ${r.route}\``, '', `- Price: ${callPrice(r.usd)} per call (x402, USDC), tool name \`${r.tool}\` over MCP`, `- Free sample: \`${F.origin}${r.sample}\``, `- Question it answers: ${r.question}`, '', r.desc, '']),
  ...F.signal_routes.flatMap((r) => [`## ${r.title}: \`GET ${r.shown}\``, '', `- Price: ${callPrice(r.usd)} per call (x402, USDC), tool name \`${r.tool}\` over MCP`, `- Free sample: \`${F.origin}${r.sample}\``, `- Question it answers: ${r.question}`, '', r.desc, '']),
  '## Passes',
  '',
  ...F.passes.flatMap((p) => [`### ${p.label}: \`GET ${p.path}\` (${money(p.usd)})`, '', `- Valid ${p.days === 1 ? '24 hours' : `${p.days} days`} from the moment the payment settles; good only on ${p.routes.map((r) => `\`${r}\``).join(', ')}; one call per route every ${p.pace_s} seconds per key.`, `- Terms as the purchase response states them: ${p.body.terms}.`, `- Use as the purchase response states it: ${p.body.use}.`, '']),
  ...(F.news_flag ? [] : ['The regulatory news brief (`/api/news-brief`) is off on this build; it joins the passes when it is switched on.', '']),
].join('\n');

const files = {
  'skills/agentfeed-briefs/SKILL.md': render(fs.readFileSync(path.join(here, 'skill.template.md'), 'utf8')),
  'skills/agentfeed-briefs/references/SCHEDULING.md': render(fs.readFileSync(path.join(here, 'scheduling.template.md'), 'utf8')),
  'skills/agentfeed-briefs/references/ROUTES.md': routesRef,
};
let drift = 0;
for (const [rel, text] of Object.entries(files)) {
  const f = path.join(root, rel);
  const body = text.endsWith('\n') ? text : `${text}\n`;
  const have = fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : null;
  if (check) { if (have !== body) { drift++; console.error(`DRIFT ${rel}`); } continue; }
  fs.mkdirSync(path.dirname(f), { recursive: true });
  if (have !== body) { fs.writeFileSync(f, body); console.log(`wrote ${rel}`); } else console.log(`same  ${rel}`);
}
if (check) { if (drift) process.exit(1); console.log(`no drift: ${Object.keys(files).length} files equal what the code at ${sha} generates`); }
